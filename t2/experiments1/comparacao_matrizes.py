# Process raw text into list of dictionaries
data = []
for line in raw_data.strip().splitlines():
    img, matrix, _, _, corr = line.split(",")
    size = int(re.search(r"(\d+)", img).group(1))
    data.append({"Imagem": img, "Matriz": matrix, "Correlacao": float(corr), "Tamanho": size})
import matplotlib.pyplot as plt
import pandas as pd
import re

# Converte para DataFrame
df = pd.DataFrame(data)

# Extrai o tamanho numérico da imagem a partir do nome
df["Tamanho"] = df["Imagem"].apply(lambda x: int(re.search(r"(\d+)", x).group(1)))

# Obtém a lista de matrizes
matrizes = df["Matriz"].unique()

# Plota
plt.figure(figsize=(12, 6))
plt.xscale("log", base=2)
for matriz in matrizes:
    subset = df[df["Matriz"] == matriz]
    matriz_name = "-".join([x.capitalize() for x in matriz.split("_")])
    plt.plot(subset["Tamanho"], subset["Correlacao"], marker="o", label=matriz_name)

# Define os valores e rótulos do eixo x
xticks = sorted(df["Tamanho"].unique())
plt.xticks(xticks, labels=[str(x) for x in xticks])

plt.xlabel("Tamanho da imagem(px)", fontsize=12)
plt.ylabel("Correlação", fontsize=12)
plt.legend()
plt.grid(True)
plt.tight_layout()
plt.savefig("correlation_vs_image_size.png")
